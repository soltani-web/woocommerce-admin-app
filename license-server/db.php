// ???? ???? ???? ????? ?? ?????? ????? ?? ???? WCAPP-XXXX-XXXX-XXXX
function generateLicenseKey(): string {
    $chars = '23456789ABCDEFGHJKLMNPQRSTUVWXYZ';
    $segments = [];
    for ($i = 0; $i < 3; $i++) {
        $segment = '';
        for ($j = 0; $j < 4; $j++) {
            $segment .= $chars[random_int(0, strlen($chars) - 1)];
        }
        $segments[] = $segment;
    }
    return 'WCAPP-' . implode('-', $segments);
}
